"""Feature preparation shared by rule-based baseline evaluators."""

from __future__ import annotations

import pandas as pd

from features.technical.structure import structure_levels

STOP_FEATURES = ("last_swing_low", "last_swing_high")


def ensure_baseline_stop_features(
    bars: pd.DataFrame,
    features: pd.DataFrame,
    *,
    swing_period: int,
) -> tuple[pd.DataFrame, tuple[str, ...]]:
    """Add causal canonical swing anchors required to construct baseline stops.

    Args:
        bars: Market bars aligned to the evaluation feature frame.
        features: Existing numeric or precomputed feature frame.
        swing_period: Configured fractal side length for structure levels.

    Returns:
        Feature frame and the stop columns generated by this helper.
    """
    if not bars.index.equals(features.index):
        raise ValueError("baseline bars and features must have identical indexes")
    missing = tuple(column for column in STOP_FEATURES if column not in features.columns)
    if not missing:
        return features, ()
    levels = structure_levels(bars, swing_period=swing_period, atr_mult=0.0)
    return features.join(levels.loc[:, list(missing)], how="left"), missing
